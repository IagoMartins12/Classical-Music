// Função melhorada para formatar número com limitação
export function formatPhoneNumberWithLimit(
  inputValue: string,
  country: PhoneCountry
): {
  formattedValue: string;
  rawDigits: string;
  isComplete: boolean;
  maxReached: boolean;
} {
  // Remove todos os caracteres não numéricos
  const digits = inputValue.replace(/\D/g, '');

  // Limita ao número máximo de dígitos do país
  const limitedDigits = digits.slice(0, country.maxDigits);

  // Aplica a formatação
  let formatted = '';
  let digitIndex = 0;

  for (
    let i = 0;
    i < country.format.length && digitIndex < limitedDigits.length;
    i++
  ) {
    const char = country.format[i];
    if (char === 'X') {
      formatted += limitedDigits[digitIndex];
      digitIndex++;
    } else {
      formatted += char;
    }
  }

  return {
    formattedValue: formatted,
    rawDigits: limitedDigits,
    isComplete: limitedDigits.length === country.maxDigits,
    maxReached: digits.length > country.maxDigits,
  };
}

// Hook personalizado para gerenciar input de telefone
export function usePhoneInput(
  country: PhoneCountry,
  onChange: (phone: string) => void
) {
  const handleInputChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const inputValue = e.target.value;

    // Formatar e limitar
    const { formattedValue, rawDigits, maxReached } =
      formatPhoneNumberWithLimit(inputValue, country);

    // Se chegou no máximo, não permitir mais entrada
    if (maxReached) {
      // Opcional: feedback visual ou sonoro de que chegou no limite
      console.log(
        `📱 Limite de ${country.maxDigits} dígitos atingido para ${country.name}`
      );
    }

    // Atualizar o valor formatado no input
    e.target.value = formattedValue;

    // Gerar telefone completo para onChange
    if (rawDigits) {
      const fullPhone = `${country.dialCode}${rawDigits}`;
      onChange(fullPhone);
    } else {
      onChange('');
    }
  };

  return { handleInputChange };
}

// Função para validar se o número está completo
export function isPhoneNumberComplete(
  phone: string,
  country: PhoneCountry
): boolean {
  const digits = phone.replace(/\D/g, '');
  const phoneWithoutCountryCode = digits.replace(
    country.dialCode.replace('+', ''),
    ''
  );
  return phoneWithoutCountryCode.length === country.maxDigits;
}

// Função para obter placeholder formatado
export function getFormattedPlaceholder(country: PhoneCountry): string {
  return country.format.replace(/X/g, '0');
}

// Função para detectar se o usuário está tentando colar um número muito longo
export function handlePhonePaste(
  pastedText: string,
  country: PhoneCountry
): {
  shouldAccept: boolean;
  processedValue: string;
  warning?: string;
} {
  const digits = pastedText.replace(/\D/g, '');

  if (digits.length <= country.maxDigits) {
    return {
      shouldAccept: true,
      processedValue: pastedText,
    };
  }

  // Se for muito longo, truncar e avisar
  const truncatedDigits = digits.slice(0, country.maxDigits);
  const { formattedValue } = formatPhoneNumberWithLimit(
    truncatedDigits,
    country
  );

  return {
    shouldAccept: true,
    processedValue: formattedValue,
    warning: `Número truncado para ${country.maxDigits} dígitos (formato ${country.name})`,
  };
}
