export function translateCountryName(englishName: string): string {
  return COUNTRY_TRANSLATIONS[englishName] || englishName;
}

// Função para aplicar tradução aos países do LocationSelector
export function translateCountryOptions(
  countries: Array<{
    value: string;
    label: string;
    extra: string;
    flag: string;
  }>
) {
  return countries.map((country) => ({
    ...country,
    label: translateCountryName(country.label),
  }));
}

