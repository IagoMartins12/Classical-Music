/** Rótulo de um tipo de evento; tipo novo na API aparece pelo próprio nome. */
export function rotuloDoTipo(idioma: Idioma, tipo: string) {
  const tipos = BLOG[idioma].agenda.tipos as Record<string, string>;
  return tipos[tipo] ?? tipo;
}
